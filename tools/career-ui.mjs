// 커리어 화면 흐름 확인: 타이틀 → 만들기 → 홈 → 4주 → 연습경기 → 결과
// node tools/career-ui.mjs <주소> <폴더>
import { chromium } from 'playwright-core';
const [url, dir] = process.argv.slice(2);
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 940 } });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (m) => m.type() === 'error' && !m.text().includes('404') && errors.push(m.text()));
page.on('dialog', (d) => d.accept());
await page.goto(url);
await page.waitForTimeout(1500);
await page.screenshot({ path: `${dir}/c1-title.png` });
await page.click('[data-act=new][data-slot="0"]');
await page.waitForTimeout(400);
await page.click('.opt[data-g=pos][data-v=PG]');
await page.click('.opt[data-g=bg][data-v=street]');
await page.click('[data-look=hair][data-d="1"]');
await page.click('[data-look=hair][data-d="1"]');
await page.click('#cAuto');
await page.waitForTimeout(300);
await page.screenshot({ path: `${dir}/c2-create.png`, fullPage: true });
await page.click('#cGo');
await page.waitForTimeout(500);
await page.screenshot({ path: `${dir}/c3-welcome.png` });
await page.click('#mbox [data-close]');
await page.waitForTimeout(300);
await page.screenshot({ path: `${dir}/c4-home.png` });
const actions = ['team', 'solo', 'weight', 'team'];
for (let i = 0; i < 4; i++) {
  await page.click(`[data-do=${actions[i]}]`);
  await page.waitForTimeout(600);
  if (i === 1) await page.screenshot({ path: `${dir}/c5-week.png` });
  await page.click('#mbox [data-close]');
  await page.waitForTimeout(300);
}
await page.screenshot({ path: `${dir}/c6-pregame.png` });
await page.click('#pgWatch');
await page.waitForTimeout(2500);
await page.screenshot({ path: `${dir}/c7-game.png` });
await page.click('#btnEnd');
await page.waitForTimeout(500);
await page.click('#btnDone');
await page.waitForTimeout(500);
await page.screenshot({ path: `${dir}/c8-result.png`, fullPage: true });
await page.click('#rNext');
await page.waitForTimeout(400);
await page.click('[data-tab=stats]');
await page.waitForTimeout(200);
for (let i = 0; i < 4; i++) await page.click('[data-inv][data-d="1"]:not([disabled])');
await page.screenshot({ path: `${dir}/c9-stats.png`, fullPage: true });
await page.click('[data-a=invest]');
await page.waitForTimeout(300);
await page.click('[data-tab=team]');
await page.screenshot({ path: `${dir}/c10-team.png` });
await page.click('[data-tab=records]');
await page.screenshot({ path: `${dir}/c11-records.png` });
const [dl] = await Promise.all([page.waitForEvent('download'), page.click('[data-a=export]')]);
const savePath = `${dir}/save.json`;
await dl.saveAs(savePath);
console.log('exported', dl.suggestedFilename());
await page.click('[data-a=title]');
await page.waitForTimeout(400);
const [fc] = await Promise.all([page.waitForEvent('filechooser'), page.click('[data-act=import][data-slot="1"]')]);
await fc.setFiles(savePath);
await page.waitForTimeout(600);
await page.click('[data-a=title]');
await page.waitForTimeout(400);
await page.screenshot({ path: `${dir}/c12-title2.png` });
await page.setViewportSize({ width: 420, height: 900 });
await page.click('[data-act=continue][data-slot="0"]');
await page.waitForTimeout(500);
await page.screenshot({ path: `${dir}/c13-phone-home.png`, fullPage: true });
console.log('errors:', errors.length ? errors : 'none');
await browser.close();
